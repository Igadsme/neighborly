import { randomUUID } from 'node:crypto'
import { BadRequestException, ForbiddenException } from '@nestjs/common'
import { ListingsService } from '../listings/listings.service'
import { PrismaService } from '../prisma/prisma.service'
import { createTestPrisma } from '../common/testing/integration-fixtures'
import { StorageService } from '../storage/storage.service'
import { pngBytes, jpegBytes, pdfBytes, storageServiceForTest } from '../storage/testing/storage-fixtures'

/**
 * Proves that a listing image survives end to end: bytes go into real object
 * storage, the row is written to real PostgreSQL, and a fresh service
 * instance reads both back. That is the property the UI depends on when a
 * page is reloaded.
 */
describe('Listing images end to end against PostgreSQL and object storage', () => {
  let prisma: PrismaService
  let storage: StorageService
  let listings: ListingsService
  let seller: string
  let category: string
  let listingId: string

  const storedKeys: string[] = []

  beforeAll(async () => {
    prisma = createTestPrisma()
    await prisma.$connect()
    storage = storageServiceForTest()
    listings = new ListingsService(prisma, storage)
    category = '50000000-0000-4000-8000-000000000901'
    await prisma.category.upsert({
      where: { id: category },
      update: {},
      create: { id: category, name: 'M4 Images', slug: 'm4-images' }
    })
    seller = randomUUID()
    await prisma.user.create({
      data: { id: seller, email: `images-${seller}@example.com`, passwordHash: '$argon2id$stub' }
    })
    await prisma.profile.create({ data: { userId: seller, firstName: 'Test', lastName: 'User' } })
  })

  afterAll(async () => {
    for (const key of storedKeys) await storage.remove(key).catch(() => undefined)
    await prisma.$disconnect()
  })

  beforeEach(async () => {
    // The id is generated by the database, so use the returned row.
    const draft = await listings.saveDraft(seller, {
      categoryId: category,
      title: 'Listing with photos',
      description: 'Enough description to be publishable'
    } as never)
    listingId = draft.id
  })

  afterEach(async () => {
    for (const key of storedKeys.splice(0)) await storage.remove(key).catch(() => undefined)
  })

  it('persists an uploaded image and returns it from the API view', async () => {
    const source = pngBytes()
    const image = await listings.addImage(seller, listingId, {
      buffer: source,
      mimetype: 'image/png'
    })
    storedKeys.push(image.objectKey)

    const detail = await listings.getForOwner(seller, listingId)
    expect(detail.images).toHaveLength(1)
    expect(detail.images?.[0].objectKey).toBe(image.objectKey)
    // The API hands the browser a same-origin URL, never a storage path.
    const media = detail.images as unknown as Array<{ url: string }>
    expect(media[0].url).toContain(`/api/v1/media/listings/${listingId}/`)
  })

  it('serves the same bytes after a fresh service instance reads the row', async () => {
    const source = jpegBytes()
    const image = await listings.addImage(seller, listingId, { buffer: source, mimetype: 'image/jpeg' })
    storedKeys.push(image.objectKey)

    // A second service instance stands in for a restart or redeploy.
    const reloaded = new ListingsService(prisma, storageServiceForTest())
    const detail = await reloaded.getForOwner(seller, listingId)
    expect(detail.images).toHaveLength(1)

    const { readStoredObject } = await import('../storage/testing/storage-fixtures')
    const bytes = await readStoredObject(detail.images![0].objectKey)
    expect(bytes.equals(source)).toBe(true)
  })

  it('publishes a listing and keeps its images visible to the public view', async () => {
    const image = await listings.addImage(seller, listingId, { buffer: pngBytes(), mimetype: 'image/png' })
    storedKeys.push(image.objectKey)
    await listings.publish(seller, listingId)

    const publicView = await listings.get(listingId)
    expect(publicView.status).toBe('PUBLISHED')
    expect(publicView.images).toHaveLength(1)

    const page = await listings.list({ query: 'Listing with photos' })
    const row = page.items.find(item => item.id === listingId)
    const media = row?.images as unknown as Array<{ url: string }> | undefined
    expect(media?.[0].url).toContain('/api/v1/media/listings/')
    expect(image.objectKey).toContain(listingId)
  })

  it('rejects a non-image by content before any row is written', async () => {
    await expect(
      listings.addImage(seller, listingId, { buffer: pdfBytes(), mimetype: 'application/pdf' })
    ).rejects.toThrow('not a JPEG, PNG, WebP, or GIF image')
    expect(await prisma.listingImage.count({ where: { listingId } })).toBe(0)
  })

  it('rejects an empty upload', async () => {
    await expect(listings.addImage(seller, listingId, { buffer: Buffer.alloc(0) })).rejects.toBeInstanceOf(
      BadRequestException
    )
    expect(await prisma.listingImage.count({ where: { listingId } })).toBe(0)
  })

  it('refuses an upload to another user listing', async () => {
    const other = randomUUID()
    await prisma.user.create({
      data: { id: other, email: `other-${other}@example.com`, passwordHash: '$argon2id$stub' }
    })
    await expect(
      listings.addImage(other, listingId, { buffer: pngBytes(), mimetype: 'image/png' })
    ).rejects.toBeInstanceOf(ForbiddenException)
  })

  it('caps the number of images on a listing', async () => {
    for (let index = 0; index < 8; index += 1) {
      const image = await listings.addImage(seller, listingId, {
        buffer: pngBytes(),
        mimetype: 'image/png'
      })
      storedKeys.push(image.objectKey)
    }
    await expect(
      listings.addImage(seller, listingId, { buffer: pngBytes(), mimetype: 'image/png' })
    ).rejects.toThrow('at most 8 images')
  })

  it('reorders images and persists the new order', async () => {
    const ids: string[] = []
    for (let index = 0; index < 3; index += 1) {
      const image = await listings.addImage(seller, listingId, {
        buffer: pngBytes(),
        mimetype: 'image/png'
      })
      storedKeys.push(image.objectKey)
      ids.push(image.id)
    }

    const reversed = [...ids].reverse()
    const ordered = await listings.reorderImages(seller, listingId, { imageIds: reversed })
    expect(ordered.map(image => image.id)).toEqual(reversed)
    expect(ordered.map(image => image.sortOrder)).toEqual([0, 1, 2])

    // The order is persisted, not just held in memory.
    const reloaded = await listings.getForOwner(seller, listingId)
    expect(reloaded.images?.map(image => image.id)).toEqual(reversed)
  })

  it('refuses a reorder that does not list every image exactly once', async () => {
    const first = await listings.addImage(seller, listingId, { buffer: pngBytes(), mimetype: 'image/png' })
    storedKeys.push(first.objectKey)
    await expect(listings.reorderImages(seller, listingId, { imageIds: [] })).rejects.toThrow(
      'every image on this listing exactly once'
    )
    await expect(
      listings.reorderImages(seller, listingId, { imageIds: [randomUUID()] })
    ).rejects.toThrow('exactly once')
  })

  it('removes an image row and its stored object', async () => {
    const keep = await listings.addImage(seller, listingId, { buffer: pngBytes(), mimetype: 'image/png' })
    const drop = await listings.addImage(seller, listingId, { buffer: jpegBytes(), mimetype: 'image/jpeg' })
    storedKeys.push(keep.objectKey)

    const remaining = await listings.removeImage(seller, listingId, drop.id)
    expect(remaining.map(image => image.id)).toEqual([keep.id])

    const { readStoredObject } = await import('../storage/testing/storage-fixtures')
    await expect(readStoredObject(drop.objectKey)).rejects.toThrow()
  })

  it('closes the sort-order gap after a removal', async () => {
    const images = []
    for (let index = 0; index < 3; index += 1) {
      const image = await listings.addImage(seller, listingId, {
        buffer: pngBytes(),
        mimetype: 'image/png'
      })
      storedKeys.push(image.objectKey)
      images.push(image)
    }

    await listings.removeImage(seller, listingId, images[0].id)
    const remaining = await prisma.listingImage.findMany({
      where: { listingId },
      orderBy: { sortOrder: 'asc' }
    })
    expect(remaining.map(image => image.sortOrder)).toEqual([0, 1])
  })

  it('refuses to attach an image row from another listing', async () => {
    const other = await listings.saveDraft(seller, {
      categoryId: category,
      title: 'Another listing',
      description: 'Another description here'
    } as never)
    const mine = await listings.addImage(seller, listingId, { buffer: pngBytes(), mimetype: 'image/png' })
    storedKeys.push(mine.objectKey)

    await expect(listings.attachImages(seller, other.id, { imageIds: [mine.id] })).rejects.toThrow(
      'do not belong to this listing'
    )
  })

  it('deletes the stored objects when a listing is permanently removed', async () => {
    const image = await listings.addImage(seller, listingId, { buffer: pngBytes(), mimetype: 'image/png' })
    const key = image.objectKey
    const { readStoredObject } = await import('../storage/testing/storage-fixtures')
    expect((await readStoredObject(key)).length).toBeGreaterThan(0)

    await listings.remove(seller, listingId)
    await expect(readStoredObject(key)).rejects.toThrow()
  })

  it('refuses an image upload for a deleted listing', async () => {
    await listings.remove(seller, listingId)
    await expect(
      listings.addImage(seller, listingId, { buffer: pngBytes(), mimetype: 'image/png' })
    ).rejects.toThrow('Listing not found')
  })
})